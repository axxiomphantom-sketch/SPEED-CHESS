import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Calendar, Check, Clock, Plus, Swords, Trophy, Users } from 'lucide-react';
import { api, ApiError, formatDate } from '../lib/api';
import { useAuth } from '../lib/auth';
import { Alert, Badge, Button, Card, Empty, Field, Loading, Modal, Tabs } from '../components/ui';

interface Tournament {
  id: string; name: string; slug: string; description: string; organizer: string | null;
  format: string; category: string; rounds: number; timeControl: string; maxPlayers: number; players: number;
  startsAt: string; registrationDeadline: string; status: string; registered: boolean; canRegister: boolean; full: boolean;
  prize: string | null;
}

const FORMAT_LABELS: Record<string, string> = {
  swiss: 'Swiss', 'single-elimination': 'Single elimination', 'double-elimination': 'Double elimination',
  'round-robin': 'Round robin', arena: 'Arena',
};

export function Tournaments() {
  const { user } = useAuth();
  const [tab, setTab] = useState<'all' | 'mine' | 'organised'>('all');
  const [tournaments, setTournaments] = useState<Tournament[] | null>(null);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');
  const [creating, setCreating] = useState(false);
  const [form, setForm] = useState({
    name: '', description: '', format: 'swiss', category: 'blitz', rounds: 5,
    initialSeconds: 180, increment: 2, maxPlayers: 32,
    startsAt: defaultDateTime(3), registrationDeadline: defaultDateTime(2), rules: '', prize: '',
  });
  const canOrganise = ['organizer', 'admin'].includes(user?.role ?? '');

  const load = async () => {
    try {
      if (tab === 'all') {
        const res = await api.get<{ tournaments: Tournament[] }>('/tournaments');
        setTournaments(res.tournaments);
      } else if (tab === 'mine') {
        const res = await api.get<{ tournaments: any[] }>('/tournaments/mine');
        setTournaments(res.tournaments);
      } else {
        const res = await api.get<{ tournaments: Tournament[] }>('/tournaments/organised');
        setTournaments(res.tournaments);
      }
    } catch { setTournaments([]); }
  };

  useEffect(() => { setTournaments(null); load(); /* eslint-disable-next-line react-hooks/exhaustive-deps */ }, [tab]);

  const register = async (tournament: Tournament) => {
    setError(''); setNotice('');
    try {
      await api.post(`/tournaments/${tournament.id}/register`);
      setNotice(`You are registered for ${tournament.name}. Pairings appear here when round one starts.`);
      load();
    } catch (err) { setError(err instanceof ApiError ? err.message : 'Registration failed.'); }
  };

  const withdraw = async (tournament: Tournament) => {
    setError(''); setNotice('');
    try {
      await api.post(`/tournaments/${tournament.id}/withdraw`);
      setNotice(`You withdrew from ${tournament.name}.`);
      load();
    } catch (err) { setError(err instanceof ApiError ? err.message : 'Withdrawal failed.'); }
  };

  const create = async () => {
    setError('');
    try {
      await api.post('/tournaments', {
        ...form,
        startsAt: new Date(form.startsAt).toISOString(),
        registrationDeadline: new Date(form.registrationDeadline).toISOString(),
      });
      setCreating(false);
      setTab('organised');
      setNotice('Tournament created. Share the link and open the first round when you are ready.');
    } catch (err) { setError(err instanceof ApiError ? err.message : 'Could not create the tournament.'); }
  };

  return (
    <div className="page">
      <header className="page-head">
        <div>
          <div className="eyebrow"><Trophy size={13} style={{ verticalAlign: -2 }} /> Competition</div>
          <h1>Tournaments</h1>
          <p>Swiss, elimination, round robin and arena events. Pairings, tiebreaks and games are generated by the platform — results update the standings automatically.</p>
        </div>
        {canOrganise && <Button onClick={() => setCreating(true)} icon={<Plus size={16} />}>Create tournament</Button>}
      </header>

      {error && <div className="form-error" role="alert">{error}</div>}
      {notice && <Alert tone="success">{notice}</Alert>}

      <Tabs value={tab} onChange={setTab} label="Tournament lists" tabs={[
        { id: 'all', label: 'Discover' },
        { id: 'mine', label: 'My entries' },
        ...(canOrganise ? [{ id: 'organised' as const, label: 'I organise' }] : []),
      ]} />

      {tournaments === null ? <Loading rows={3} /> : tournaments.length === 0 ? (
        <Empty icon={<Trophy size={26} />} title={tab === 'all' ? 'No tournaments open right now' : tab === 'mine' ? 'You have not entered a tournament' : 'You have not organised a tournament'}>
          {tab === 'all' ? 'Organisers publish new events regularly — check back soon.' : tab === 'mine' ? 'Browse the discover tab and join an event.' : 'Create your first event to see it here.'}
        </Empty>
      ) : (
        <div className="grid grid-auto">
          {tournaments.map(tournament => (
            <Card key={tournament.id} hover>
              <div className="row-between" style={{ marginBottom: 8 }}>
                <Badge tone={tournament.status === 'ongoing' ? 'success' : tournament.status === 'completed' ? 'muted' : 'purple'}>
                  {tournament.status}
                </Badge>
                <span className="tiny muted">{FORMAT_LABELS[tournament.format] ?? tournament.format}</span>
              </div>
              <h3 style={{ marginBottom: 4, fontSize: '1.05rem' }}>{tournament.name}</h3>
              <p className="small muted" style={{ minHeight: 40 }}>{tournament.description.slice(0, 120)}{tournament.description.length > 120 ? '…' : ''}</p>
              <div className="stack" style={{ gap: 6, fontSize: '.82rem' }}>
                <div className="row-between"><span className="muted"><Calendar size={12} style={{ verticalAlign: -1 }} /> Starts</span><span style={{ fontWeight: 600 }}>{formatDate(tournament.startsAt)}</span></div>
                <div className="row-between"><span className="muted"><Clock size={12} style={{ verticalAlign: -1 }} /> Time control</span><span style={{ fontWeight: 600 }}>{tournament.timeControl} {tournament.category}</span></div>
                <div className="row-between"><span className="muted"><Users size={12} style={{ verticalAlign: -1 }} /> Players</span><span style={{ fontWeight: 600 }}>{tournament.players}/{tournament.maxPlayers}</span></div>
                <div className="row-between"><span className="muted"><Swords size={12} style={{ verticalAlign: -1 }} /> Rounds</span><span style={{ fontWeight: 600 }}>{tournament.rounds}</span></div>
              </div>
              <div className="row mt-2" style={{ gap: 6 }}>
                <Link to={`/tournaments/${tournament.slug}`} className="btn btn-secondary btn-sm grow">Details</Link>
                {tournament.registered ? (
                  <Button size="sm" variant="success" icon={<Check size={14} />} disabled>Entered</Button>
                ) : tournament.canRegister && !tournament.full ? (
                  <Button size="sm" onClick={() => register(tournament)}>Register</Button>
                ) : (
                  <Button size="sm" variant="secondary" disabled>{tournament.full ? 'Full' : 'Closed'}</Button>
                )}
              </div>
              {tournament.registered && tournament.status === 'upcoming' && (
                <button type="button" className="btn btn-ghost btn-sm btn-block mt-1" onClick={() => withdraw(tournament)}>Withdraw</button>
              )}
            </Card>
          ))}
        </div>
      )}

      <Modal open={creating} onClose={() => setCreating(false)} title="Create a tournament"
        footer={<><Button variant="secondary" onClick={() => setCreating(false)}>Cancel</Button><Button onClick={create}>Create</Button></>}>
        <Field label="Name" htmlFor="t-name"><input id="t-name" className="input" value={form.name} onChange={e => setForm({ ...form, name: e.target.value })} /></Field>
        <Field label="Description" htmlFor="t-desc"><textarea id="t-desc" className="textarea" value={form.description} onChange={e => setForm({ ...form, description: e.target.value })} /></Field>
        <div className="grid grid-2" style={{ gap: 12 }}>
          <Field label="Format" htmlFor="t-format">
            <select id="t-format" className="select" value={form.format} onChange={e => setForm({ ...form, format: e.target.value })}>
              {Object.entries(FORMAT_LABELS).map(([value, label]) => <option key={value} value={value}>{label}</option>)}
            </select>
          </Field>
          <Field label="Time control" htmlFor="t-cat">
            <select id="t-cat" className="select" value={form.category} onChange={e => setForm({ ...form, category: e.target.value })}>
              {['bullet', 'blitz', 'rapid', 'classical'].map(c => <option key={c} value={c}>{c}</option>)}
            </select>
          </Field>
          <Field label="Rounds" htmlFor="t-rounds"><input id="t-rounds" className="input" type="number" min={1} max={15} value={form.rounds} onChange={e => setForm({ ...form, rounds: Number(e.target.value) })} /></Field>
          <Field label="Max players" htmlFor="t-max"><input id="t-max" className="input" type="number" min={2} max={255} value={form.maxPlayers} onChange={e => setForm({ ...form, maxPlayers: Number(e.target.value) })} /></Field>
          <Field label="Starts" htmlFor="t-starts"><input id="t-starts" className="input" type="datetime-local" value={form.startsAt} onChange={e => setForm({ ...form, startsAt: e.target.value })} /></Field>
          <Field label="Registration closes" htmlFor="t-deadline"><input id="t-deadline" className="input" type="datetime-local" value={form.registrationDeadline} onChange={e => setForm({ ...form, registrationDeadline: e.target.value })} /></Field>
        </div>
        <Field label="Rules (optional)" htmlFor="t-rules"><textarea id="t-rules" className="textarea" value={form.rules} onChange={e => setForm({ ...form, rules: e.target.value })} /></Field>
        <Field label="Prize (optional)" htmlFor="t-prize"><input id="t-prize" className="input" value={form.prize} onChange={e => setForm({ ...form, prize: e.target.value })} /></Field>
      </Modal>
    </div>
  );
}

function defaultDateTime(daysAhead: number) {
  const date = new Date(Date.now() + daysAhead * 864e5);
  date.setMinutes(0, 0, 0);
  const offset = date.getTimezoneOffset() * 60000;
  return new Date(date.getTime() - offset).toISOString().slice(0, 16);
}
